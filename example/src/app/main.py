def demo_error_messages():
    """Demonstrate error message translations."""
    print("❌ Error Messages")
    print("=" * 40)

    t_en = get_translations(Languages.EN)
    t_es = get_translations(Languages.ES)
    t_fr = get_translations(Languages.FR)

    errors = ["not_found", "unauthorized", "server_error", "network_error"]

    for error in errors:
        print(f"{error}:")
        print(f"  EN: {getattr(t_en.errors, error)}")
        print(f"  ES: {getattr(t_es.errors, error)}")
        print(f"  FR: {getattr(t_fr.errors, error)}")
        print()


def demo_dynamic_language_selection():
    """Demonstrate dynamic language selection."""
    print("🌐 Dynamic Language Selection")
    print("=" * 40)

    # Simulate user language preferences
    user_languages = ["en", "es", "fr"]

    for lang_code in user_languages:
        # Convert string to enum
        try:
            language = Languages(lang_code)
            t = get_translations(language)

            print(f"Language: {lang_code.upper()}")
            print(f"  Welcome: {t.welcome.message}")
            print(f"  Status: {t.status.online}")
            print()

        except ValueError:
            print(f"Unsupported language: {lang_code}")


