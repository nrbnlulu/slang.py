"""
Example usage of the Slang internationalization library.

This example demonstrates how to use type-safe translations generated by Slang.
Run `slang generate` first to create the translation files.
"""

from .__tr__.translations import get_translations, Languages


def demo_basic_usage():
    """Demonstrate basic translation usage."""
    print("🌍 Basic Translation Usage")
    print("=" * 40)

    # Get English translations
    t_en = get_translations(Languages.EN)
    print(f"English: {t_en.welcome.title}")
    print(f"English: {t_en.app.name} - {t_en.app.tagline}")

    # Get Spanish translations
    t_es = get_translations(Languages.ES)
    print(f"Spanish: {t_es.welcome.title}")
    print(f"Spanish: {t_es.app.name} - {t_es.app.tagline}")

    # Get French translations
    t_fr = get_translations(Languages.FR)
    print(f"French: {t_fr.welcome.title}")
    print(f"French: {t_fr.app.name} - {t_fr.app.tagline}")
    print()


def demo_parameterized_translations():
    """Demonstrate parameterized translations with type safety."""
    print("🔧 Parameterized Translations")
    print("=" * 40)

    # Auto-detected parameters (using {placeholder} syntax)
    t_en = get_translations(Languages.EN)
    t_es = get_translations(Languages.ES)
    t_fr = get_translations(Languages.FR)

    name = "Alice"
    print(f"English: {t_en.greetings.hello(name=name)}")
    print(f"Spanish: {t_es.greetings.hello(name=name)}")
    print(f"French: {t_fr.greetings.hello(name=name)}")
    print()

    # Explicit parameters with type annotations
    message_count = 5
    print(f"English: {t_en.messages.count(count=message_count)}")
    print(f"Spanish: {t_es.messages.count(count=message_count)}")
    print(f"French: {t_fr.messages.count(count=message_count)}")
    print()

    # Complex parameters
    unread_count = 3
    print(f"English: {t_en.messages.unread(unread=unread_count)}")
    print(f"Spanish: {t_es.messages.unread(unread=unread_count)}")
    print(f"French: {t_fr.messages.unread(unread=unread_count)}")
    print()


