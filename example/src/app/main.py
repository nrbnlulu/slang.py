def demo_type_safety():
    """Demonstrate type safety features."""
    print("🛡️  Type Safety Demonstration")
    print("=" * 40)

    t = get_translations(Languages.EN)

    # This works - correct usage
    print("✅ Correct usage:")
    print(f"  {t.messages.count(count=5)}")
    print(f"  {t.greetings.hello(name='Alice')}")
    print()

    # These would cause type errors in a type checker:
    print("❌ These would be caught by type checkers:")
    print("  # t.messages.count(count='invalid')  # Wrong type")
    print("  # t.nonexistent.field  # Field doesn't exist")
    print("  # t.greetings.hello()  # Missing required parameter")
    print()


